def ability_modifier(score: int) -> int:
    """Модификатор характеристики: (значение − 10) // 2."""
    return (int(score) - 10) // 2


def format_modifier(value: int) -> str:
    """Форматирует модификатор со знаком: 2 -> '+2', -1 -> '-1'."""
    return f"{value:+d}"


def proficiency_bonus(level: int) -> int:
    """Бонус мастерства по уровню персонажа (1–20)."""
    level = max(1, min(int(level), MAX_LEVEL))
    return 2 + (level - 1) // 4


def xp_threshold(level: int) -> int:
    """Сколько всего XP нужно, чтобы достичь указанного уровня."""
    level = max(1, min(int(level), MAX_LEVEL))
    return XP_THRESHOLDS[level]


def next_xp_threshold(level: int) -> Optional[int]:
    """Порог XP для следующего уровня (None на 20-м уровне)."""
    if level >= MAX_LEVEL:
        return None
    return XP_THRESHOLDS[level + 1]


def level_for_xp(xp: int) -> int:
    """Определяет уровень по накопленному опыту."""
    xp = max(0, int(xp))
    level = 1
    for candidate in range(2, MAX_LEVEL + 1):
        if xp >= XP_THRESHOLDS[candidate]:
            level = candidate
        else:
            break
    return level


def normalize_ability_key(key: str) -> Optional[str]:
    """Приводит название характеристики (сил/СИЛ/strength) к коду ('str')."""
    return ABILITY_ALIASES.get(str(key).strip().lower())


def resolve_class_key(class_name: str) -> Optional[str]:
    """Пытается сопоставить произвольное название класса с известным ключом."""
    if not class_name:
        return None
    lowered = str(class_name).strip().lower()
    if lowered in CLASSES:
        return lowered
    for key, data in CLASSES.items():
        for alias in data.get("aliases", ()):
            if alias in lowered:
                return key
    return None


def hit_die_sides(class_name: str) -> int:
    """Кость хитов класса (число граней). Для неизвестного класса — d8."""
    key = resolve_class_key(class_name)
    if key is None:
        return DEFAULT_HIT_DIE
    return int(CLASSES[key]["hit_die"])


def average_hit_points(sides: int, con_mod: int) -> int:
    """Прирост HP за уровень: среднее по кости хитов + модификатор ТЕЛ (минимум 1)."""
    return max(1, int(sides) // 2 + 1 + int(con_mod))


